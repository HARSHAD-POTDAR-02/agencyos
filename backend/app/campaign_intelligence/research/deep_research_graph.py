class ResearchSubTopic(BaseModel):
    """A focused sub-investigation facet decomposed from the user's research query."""
    topic_id: str = Field(description="Unique short identifier, e.g. 'topic_subko_pricing'")
    title: str = Field(description="Descriptive title of the sub-investigation")
    target_entity: str | None = Field(default=None, description="Specific competitor, brand, or concept")
    research_questions: list[str] = Field(description="1-2 explicit factual questions to answer")
    suggested_queries: list[str] = Field(description="1-2 highly targeted search queries")
    max_tool_budget: int = Field(default=2, ge=1, le=3, description="Tool calls allocated for this facet")
    evidence_type: str = Field(
        default="general",
        description="Type of evidence sought: 'official_menu_or_store', 'independent_reviews', 'directory_or_outlets', or 'press_and_positioning'",
    )


class DeepResearchPlan(BaseModel):
    """Master research plan generated by the Supervisor node."""
    plan_summary: str = Field(description="Brief strategic rationale for this research decomposition")
    sub_topics: list[ResearchSubTopic] = Field(
        default_factory=list,
        max_length=4,
        description="Structured sub-topics ensuring all named entities and core dimensions are investigated",
    )
    is_ambiguous_clarification: bool = Field(
        default=False,
        description="True if planning halted to request essential clarification from user on business category",
    )
    research_mode: ResearchScopeMode = Field(
        default=ResearchScopeMode.CLIENT_SCOPED,
        description="Resolved research mode for this investigation",
    )


class TopicEvidence(BaseModel):
    """Isolated evidence dossier collected by a sub-researcher."""
    topic_id: str
    topic_title: str
    target_entity: str | None = None
    findings: list[str] = Field(default_factory=list)
    key_excerpts: list[str] = Field(default_factory=list)
    detected_metrics: list[str] = Field(default_factory=list)
    inspected_sources: list[str] = Field(default_factory=list)
    snippet_sources: list[str] = Field(default_factory=list)
    status: Literal["answered", "partial", "missing"] = "answered"
    summary: str = ""


class DeepResearchState(TypedDict):
    """LangGraph execution state for the Deep Research workflow."""
    query: str
    context: CampaignStudioContext
    plan: DeepResearchPlan | None
    current_topic_idx: int
    used_tool_budget: int
