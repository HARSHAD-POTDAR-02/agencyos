def _resolve_research_mode(
    query: str,
    context: CampaignStudioContext | None,
) -> tuple[ResearchScopeMode, bool]:
    """
    Resolve research mode across 3 explicit scopes:
    1. CLIENT_SCOPED: Research the active client's market, competitors, or offerings.
    2. CLIENT_INFORMED_EXTERNAL: Research external trends or practices using client industry/location as context.
    3. INDEPENDENT_RESEARCH: Explicitly named external subjects take precedence over client context.
    
    Returns:
        (mode, is_ambiguous): If mode is CLIENT_SCOPED but the active client lacks an industry/category,
        and the query is an open-ended competitor question, is_ambiguous is True.
    """
    q = query.lower()

    # Priority 0: Explicit negative client instructions
    negative_client_cues = [
        r"\bdo not relate\b",
        r"\bnot relate\b",
        r"\bdo not connect\b",
        r"\bignore client\b",
        r"\bindependent of\b",
        r"\bwithout client\b",
        r"\bnot related to\b",
    ]
    if any(re.search(pat, q) for pat in negative_client_cues):
        return ResearchScopeMode.INDEPENDENT_RESEARCH, False

    client_name = context.client_name if context else ""
    client_industry = (context.client_industry if context else "") or ""
    cleaned_client = re.sub(r"[^\w\s]", "", client_name.lower()).strip()

    client_cues = {
        "our competitors", "who are our competitors", "what are our competitors",
        "what are our direct and indirect competitors", "our direct competitors",
        "who is our competition", "my client", "our client", "the client",
        "our brand", "our restaurant", "our cafe", "our company", "our business",
        "our product", "our pricing", "our location", "around us", "for us",
        "we offer", "we are", "we're", "our service", "our shop", "our agency client",
    }
    has_client_cue = any(cue in q for cue in client_cues) or (len(cleaned_client) >= 4 and cleaned_client in q)

    # Priority 1: Hybrid Client-Informed External (e.g. "Based on coffee research, what opportunities could Hotel Shauryawada explore?")
    hybrid_external_cues = [
        r"\bbased on\b",
        r"\bwhat opportunities could\b",
        r"\bwhat can\s+[a-z0-9\s,&-]+\s+learn\b",
        r"\bhow can\s+[a-z0-9\s,&-]+\s+(?:adopt|explore|apply|leverage)\b",
        r"\bopportunities\s+for\s+[a-z0-9\s,&-]+\s+from\b",
        r"\bwhat\s+[a-z0-9\s,&-]+\s+could\s+[a-z0-9\s,&-]+\s+(?:adopt|explore)\b",
    ]
    is_hybrid_query = any(re.search(pat, q) for pat in hybrid_external_cues) and (has_client_cue or (len(cleaned_client) >= 4 and cleaned_client in q))
    if is_hybrid_query:
        return ResearchScopeMode.CLIENT_INFORMED_EXTERNAL, False

    # Priority 2: Explicit user-named external subjects take priority over unrelated client context
    named_external_cues = [
        r"\bspecifically\b",
        r"\bcompare\s+[a-z0-9\s,&-]+(?:\sand\s|\svs\s)",
        r"\b(?:between|across)\s+[a-z0-9\s,&-]+(?:\sand\s|\svs\s)",
        r"\bcompeting with\b",
        r"\bfor\s+(?:an?\s+)?[a-z0-9\s,&-]+(?:dining|restaurant|coffee|cafe|bakery|clinic|salon|fitness|meal-prep|gym)\b",
        r"\b(?:analysis|research)\s+on\s+[a-z0-9\s,&-]+(?:dining|restaurant|coffee|cafe|bakery|clinic|salon|fitness|meal-prep|gym|service|brand|roaster|roasters)\b",
    ]
    if any(re.search(pat, q) for pat in named_external_cues):
        return ResearchScopeMode.INDEPENDENT_RESEARCH, False

    # Check for trend/benchmarks (CLIENT_INFORMED_EXTERNAL)
    trend_cues = {"trend", "trends", "viral", "hooks", "benchmark", "benchmarks", "format", "formats", "growth", "playbook"}
    is_trend_query = any(t in q for t in trend_cues)

    if has_client_cue:
        # Check Ambiguity Gate:
        # If the active client's business category/industry is missing, and the question is an open competitor query,
        # we cannot identify direct/indirect competitors without guessing. Halt and ask for clarification.
        is_open_comp_query = any(k in q for k in (
            "competitor", "competitors", "competition", "rivals", "who are we against", "who do we compete with"
        ))
        is_industry_missing = (
            not client_industry
            or client_industry.strip().lower() in ("", "unknown", "none", "general", "general business")
        )
        if is_open_comp_query and is_industry_missing:
            return ResearchScopeMode.CLIENT_SCOPED, True
        return ResearchScopeMode.CLIENT_SCOPED, False

    if is_trend_query:
        return ResearchScopeMode.CLIENT_INFORMED_EXTERNAL, False

    # Default fallback
    if client_name:
        is_open_comp_query = any(k in q for k in ("competitor", "competitors", "competition"))
        is_industry_missing = (
            not client_industry
            or client_industry.strip().lower() in ("", "unknown", "none", "general", "general business")
        )
        if is_open_comp_query and is_industry_missing:
            return ResearchScopeMode.CLIENT_SCOPED, True
        return ResearchScopeMode.CLIENT_SCOPED, False

    return ResearchScopeMode.INDEPENDENT_RESEARCH, False


def _build_deep_research_prior_context(
    context: CampaignStudioContext | None,
    query: str = "",
    mode: ResearchScopeMode = ResearchScopeMode.CLIENT_SCOPED,
) -> str:
    """Build a prior-context prompt block from active artifact only if strictly relevant."""
    if not context or not (
        context.active_artifact_payload
        and context.active_artifact_type == ArtifactType.research_evidence.value
    ):
        return ""

    payload = context.active_artifact_payload
    prior_topic = str(payload.get("query_topic") or "").lower()
    q = query.lower()

    followup_cues = {
        "the second", "the first", "the third", "tell me more", "continue",
        "earlier", "previous", "elaborate", "drill down", "deep dive",
        "expand on", "what about competitor", "why did you", "what did you find",
    }
    is_followup = any(cue in q for cue in followup_cues)

    prior_words = {w for w in re.findall(r"\w{4,}", prior_topic) if w not in {"what", "when", "where", "which", "with", "from", "about"}}
    query_words = {w for w in re.findall(r"\w{4,}", q) if w not in {"what", "when", "where", "which", "with", "from", "about"}}
    has_topic_overlap = bool(prior_words.intersection(query_words))

    # For independent research, do NOT inject prior session artifacts unless user explicitly asks a follow-up
    if mode == ResearchScopeMode.INDEPENDENT_RESEARCH and not is_followup:
        return ""

    # For client-scoped research, require either an explicit follow-up cue or substantive topic overlap
    if mode == ResearchScopeMode.CLIENT_SCOPED and not is_followup and not has_topic_overlap:
        logger.info("Discarding prior research artifact: topic does not overlap with prior topic '%s'", prior_topic[:40])
        return ""

    prev_competitors = [
        f"  - {c.get('competitor_name')} on {c.get('platform')}: {c.get('observed_creative_angle')}"
        f" [source: {c.get('citation', {}).get('source_url', 'unknown')}]"
        for c in payload.get("observed_competitors", [])
    ]
    lines = ["\nPRIOR RESEARCH CONTEXT IN THIS SESSION (from previous turn):"]
    lines.append(f"- Query Topic: {payload.get('query_topic', 'Unknown')}")
    if prev_competitors:
        lines.append("- Previously Observed Competitors:")
        lines.extend(prev_competitors[:4])
    lines.append(
        "If the user refers to a previous finding (e.g. 'the second competitor' or 'drill down into X'), "
        "build upon the prior evidence listed above.\n"
    )
    return "\n".join(lines)


def _format_brand_context_block(context: CampaignStudioContext | None, query: str) -> str:
    """Format the active studio client context for research supervisor and editorial synthesis."""
    if not context or not context.client_name:
        return ""
    
    client_name = context.client_name.strip()
    industry = (context.client_industry or "General Business").strip()
    location = (context.client_location or "").strip()
    brief = context.campaign_brief
    target_audience = brief.target_audience if (brief and brief.target_audience) else []
    brand_ctx = context.brand_context
    pillars = brand_ctx.content_pillars if (brand_ctx and brand_ctx.content_pillars) else []
    facts = brand_ctx.confirmed_facts if (brand_ctx and brand_ctx.confirmed_facts) else []

    facts_line = f"\n- Confirmed Brand Facts: {'; '.join(facts[:5])}" if facts else ""
    pillars_line = f"\n- Content Pillars / Focus: {', '.join(pillars[:4])}" if pillars else ""
    audience_line = f"\n- Target Audience: {', '.join(target_audience[:3])}" if target_audience else ""
    loc_line = f"\n- Operating Location: {location}" if location else ""

    return (
        f"--- ACTIVE CLIENT BRAND (CAMPAIGN STUDIO WORKSPACE) ---\n"
        f"- Brand Name: {client_name}\n"
        f"- Industry / Category: {industry}"
        f"{loc_line}"
        f"{audience_line}"
        f"{pillars_line}"
        f"{facts_line}\n\n"
        f"CRITICAL BRAND GROUNDING RULES:\n"
        f"1. When the user asks about 'our brand', 'our business', 'our restaurant', 'our competitors', 'we', 'us', "
        f"or asks open-ended questions like 'what are our direct and indirect competitors?' or 'who are our rivals?', "
        f"'our' refers EXCLUSIVELY to the active client brand: {client_name} ({industry}{f' in {location}' if location else ''}).\n"
        f"2. Never confuse 'our brand' with AgencyOS, software, or tech SaaS. AgencyOS is the agency execution workspace; "
        f"the market research is conducted for {client_name}.\n"
        f"3. Decompose and investigate actual competitors operating within {client_name}'s specific industry category "
        f"({industry}) and geographic market ({location or 'regional market'})."
    )


