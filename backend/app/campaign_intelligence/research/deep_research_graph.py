def _select_best_url_for_topic(
    results: list[dict[str, Any]],
    topic_title: str,
    target_entity: str | None,
    already_inspected: set[str],
    evidence_type: str = "general",
) -> str | None:
    """
    Dynamically select the highest-quality candidate webpage URL for deep inspection.
    Takes into account the pre-flight evidence_type:
    - For 'independent_reviews': penalizes official brand homepages (which never publish complaints),
      and boosts review aggregators, consumer forums, and independent review threads.
    - For 'official_menu_or_store': boosts official entity domains with /menu, /shop, /store paths.
    - For 'directory_or_outlets': boosts store locator and outlet directory pages.
    """
    BLOCKED_HOST_DOMAINS = (
        "wikipedia.org", "youtube.com", "instagram.com", "facebook.com",
        "linkedin.com", "twitter.com", "x.com", "tiktok.com", "pinterest.com",
    )
    LOW_QUALITY_HOST_SUBSTRINGS = (
        "aggregator-hub", "menuprices-scam", "foodindexing-auto",
    )

    STOPWORDS = {"the", "and", "for", "with", "from", "near", "best", "top", "online", "services", "pricing", "delivery", "plan", "plans"}
    raw_text = f"{target_entity or ''} {topic_title}".lower()
    entity_tokens = {
        token for token in re.findall(r"[a-z0-9]{3,}", raw_text)
        if token not in STOPWORDS
    }

    scored_candidates: list[tuple[float, str]] = []

    for r in results:
        u = r.get("url", "")
        if not u:
            continue
        canon = _normalize_url(u)
        if canon in already_inspected:
            continue

        u_lower = u.lower()
        try:
            parsed = urlparse(u_lower)
            netloc = parsed.netloc or ""
            path = parsed.path or ""
        except Exception:
            netloc = ""
            path = ""

        if any(netloc == bd or netloc.endswith("." + bd) for bd in BLOCKED_HOST_DOMAINS):
            continue

        score = float(r.get("score", 0.0)) * 5.0
        snippet = (r.get("content") or r.get("snippet", "")).lower()
        title = (r.get("title") or "").lower()

        if len(snippet) > 80:
            score += 2.0

        is_official_entity_domain = any(token in netloc for token in entity_tokens)

        # Context-aware evidence type scoring
        if evidence_type == "independent_reviews":
            if is_official_entity_domain:
                score -= 8.0  # Official brand homepages do not host negative customer complaints
            if any(w in u_lower or w in snippet or w in title for w in (
                "review", "reviews", "complaint", "complaints", "feedback", "rating",
                "ratings", "delay", "issue", "issues", "problem", "forum", "reddit",
                "trustpilot", "mouthshut", "consumer"
            )):
                score += 10.0
        elif evidence_type == "official_menu_or_store":
            if is_official_entity_domain:
                score += 12.0
            if any(w in u_lower or w in path for w in ("menu", "shop", "store", "product", "pricing", "subscription", "order", "collections")):
                score += 8.0
        elif evidence_type == "directory_or_outlets":
            if any(w in u_lower or w in path for w in ("location", "locations", "outlets", "cafes", "stores", "branches", "find-us")):
                score += 8.0
            if is_official_entity_domain:
                score += 6.0
        else:
            if is_official_entity_domain:
                score += 10.0
            elif any(token in path for token in entity_tokens):
                score += 3.0

        if any(lq in netloc for lq in LOW_QUALITY_HOST_SUBSTRINGS):
            score -= 5.0

        scored_candidates.append((score, u))

    if not scored_candidates:
        return None

    scored_candidates.sort(key=lambda x: x[0], reverse=True)
    return scored_candidates[0][1]


async def topic_worker_node(state: DeepResearchState) -> dict[str, Any]:
    """
    Focused sub-researcher worker that investigates a single facet of the research plan.
    Executes targeted web searches and deeply inspects discovered primary competitor pages.
    Guarantees strict per-topic evidence isolation to eliminate cross-topic contamination.
    """
    plan = state.get("plan")
    idx = state.get("current_topic_idx", 0)
    on_event = state.get("on_event_fn")
    
    if not plan or idx >= len(plan.sub_topics) or plan.is_ambiguous_clarification:
        return {}

    topic = plan.sub_topics[idx]
    logs = [f"Sub-Researcher [{idx+1}/{len(plan.sub_topics)}]: Investigating '{topic.title}' (evidence: {topic.evidence_type})"]

    if on_event:
        try:
            await on_event({
                "type": "turn_start",
                "message": f"Sub-Researcher [{idx+1}/{len(plan.sub_topics)}]: Investigating '{topic.title}'...",
            })
        except Exception:
            pass

    context = state.get("context")
    ctx = ToolExecutionContext(
        agency_id=context.agency_id if context else uuid.uuid4(),
        client_id=context.client_id if context else uuid.uuid4(),
        campaign_id=context.campaign_id if context else uuid.uuid4(),
        specialist_id="market_research",
        environment="production",
        studio_context=context,
    )

    discovered = dict(state.get("discovered_sources", {}))
    inspected = dict(state.get("inspected_sources", {}))
    tools_used = 0

    topic_discovered: dict[str, Any] = {}
    topic_inspected: dict[str, Any] = {}

    # Step A: Execute focused web search with query refinement for evidence type
    search_q = topic.suggested_queries[0] if topic.suggested_queries else f"{topic.title} {state['query'][:30]}"
    if topic.evidence_type == "independent_reviews":
        if not any(k in search_q.lower() for k in ("review", "reviews", "complaint", "complaints", "issue", "delay", "feedback")):
            search_q = f"{search_q} reviews complaints issues"

    logs.append(f"  Tool: web_search -> '{search_q}'")
    
    if on_event:
        try:
            await on_event({
                "type": "tool_start",
                "tool": "web_search",
                "message": f"Searching web for '{search_q}'",
            })
        except Exception:
            pass

    t0 = time.perf_counter()
    search_res = await web_search_handler(WebSearchInput(query=search_q, max_results=5), ctx)
    dur_ms = int((time.perf_counter() - t0) * 1000)
    tools_used += 1

    search_results_list = []
    if isinstance(search_res, dict):
        search_results_list = search_res.get("results", [])
        for r in search_results_list:
            u = r.get("url", "")
            if u:
                canon = _normalize_url(u)
                topic_discovered[canon] = r
                discovered[canon] = r

    # Select high-value candidate URL dynamically
    already_inspected_keys = set(inspected.keys())
    top_extract_url = _select_best_url_for_topic(
        results=search_results_list,
        topic_title=topic.title,
        target_entity=topic.target_entity,
        already_inspected=already_inspected_keys,
        evidence_type=topic.evidence_type,
    )

    # Step B: Deeply inspect primary webpage if tool budget allows
    budget_remaining = state["max_global_budget"] - (state["used_tool_budget"] + tools_used)
    if top_extract_url and tools_used < topic.max_tool_budget and budget_remaining > 0:
        logs.append(f"  Tool: extract_webpages -> '{top_extract_url[:60]}...'")
        if on_event:
            try:
                await on_event({
                    "type": "tool_start",
                    "tool": "extract_webpages",
                    "message": f"Inspecting primary evidence page ({top_extract_url[:50]}...)",
                })
            except Exception:
                pass

        ext_res = await extract_webpages_handler(ExtractWebpagesInput(urls=[top_extract_url]), ctx)
        tools_used += 1
        if isinstance(ext_res, dict):
            pages = ext_res.get("pages", [])
            for p in pages:
                u = p.get("url", "")
                if u:
                    canon = _normalize_url(u)
                    topic_inspected[canon] = p
                    inspected[canon] = p
                    discovered[canon] = p

    # Step C: Build TopicEvidence dossier (strictly isolated to this topic)
    findings: list[str] = []
    key_excerpts: list[str] = []
    metrics: list[str] = []

    # Priority 1: Use deeply inspected pages for this specific topic
    for canon, p in topic_inspected.items():
        summary_val = p.get("summary")
        if summary_val and is_substantive_content_line(summary_val):
            findings.append(f"{p.get('title', 'Page')}: {summary_val}")
        for ex in p.get("key_excerpts", []):
            if is_substantive_content_line(ex):
                key_excerpts.append(ex)
        metrics.extend(p.get("extracted_metrics", []))

    # Priority 2: Complement with search snippets gathered for this topic if needed
    if not findings and topic_discovered:
        for canon, r in list(topic_discovered.items())[:3]:
            snip = r.get("content") or r.get("snippet", "")
            if snip and is_substantive_content_line(snip):
                findings.append(f"{r.get('title', 'Source')}: {snip[:200]}")

    status_val: Literal["answered", "partial", "missing"] = "answered"
    if not topic_inspected and not findings:
        status_val = "missing"
    elif not topic_inspected:
        status_val = "partial"

    topic_ev = TopicEvidence(
        topic_id=topic.topic_id,
        topic_title=topic.title,
        target_entity=topic.target_entity,
        findings=findings[:4],
        key_excerpts=key_excerpts[:4],
        detected_metrics=list(set(metrics))[:6],
        inspected_sources=list(topic_inspected.keys()),
        snippet_sources=list(topic_discovered.keys()),
        status=status_val,
        summary=findings[0] if findings else "Evidence collected from search snippets.",
    )

    return {
        "current_topic_idx": idx + 1,
        "used_tool_budget": state["used_tool_budget"] + tools_used,
        "topic_evidences": [topic_ev],
        "discovered_sources": discovered,
        "inspected_sources": inspected,
        "activity_logs": logs,
    }


# ===========================================================================
# 5. Conditional Router
# ===========================================================================

def route_topics(state: DeepResearchState) -> Literal["topic_worker", "compile_report"]:
    """Determines whether to investigate the next sub-topic or transition to final report compilation."""
    plan = state.get("plan")
    if not plan or plan.is_ambiguous_clarification:
        return "compile_report"
    idx = state.get("current_topic_idx", 0)
    used = state.get("used_tool_budget", 0)
    limit = state.get("max_global_budget", 6)

    if idx < len(plan.sub_topics) and used < limit:
        return "topic_worker"
    return "compile_report"


# ===========================================================================
# 6. Editorial Compiler Node: Multi-Topic Dossier Synthesis
# ===========================================================================

async def compile_report_node(state: DeepResearchState) -> dict[str, Any]:
    """
    Synthesizes the multi-topic evidence dossiers into a publication-grade intelligence report.
    Applies strict post-validation:
    1. Ambiguity handling: Returns prompt clarification if business category was missing.
    2. Honest failure fallback: Explicitly reports zero sources if search returned empty.
    3. Channel vs Direct Competitor: Classifies delivery aggregators (Zomato/Swiggy) as CHANNEL.
    4. Review Integrity: Distinguishes 1 review (anecdote) from 2-4 (repeated) and 5+ (recurring).
    5. Numerical Claim Verification: Numbers not grounded in inspected evidence labeled unverified.
    6. Recommendation Discipline: Opportunities default to HYPOTHESIS with low-risk test methods.
    """
    query = state["query"]
    plan = state.get("plan")
    context = state.get("context")
    on_event = state.get("on_event_fn")

    # Ambiguity Gate: If planning halted to clarify business category, return clarification response immediately
    if plan and plan.is_ambiguous_clarification:
        client_name = (context.client_name if context else None) or "the client brand"
        clarification_msg = (
            f"To identify direct and indirect competitors for **{client_name}**, please clarify the primary business category "
            f"(e.g., dining restaurant, lodging hotel, cafe, or catering service). "
            f"Once the category is confirmed, competitive analysis can be precisely targeted."
        )
        synthesis = MarketResearchSynthesisOutput(
            executive_summary=clarification_msg,
            key_findings=[
                CitedKeyFinding(
                    finding=f"Business category for {client_name} is required to map direct and indirect competitors without assumptions.",
                    source_url=None,
                )
            ],
            observed_competitors=[],
            inferred_opportunities=[],
            research_dimensions=[
                ResearchDimensionItem(
                    dimension="Business Category & Scope",
                    status=ResearchDimensionStatus.NOT_AVAILABLE,
                    summary="Client industry category not provided in workspace context.",
                )
            ],
            search_limitations="Research paused pending user clarification on business category.",
        )
        return {
            "synthesis": synthesis,
            "final_report": clarification_msg,
            "activity_logs": [f"Deep Research Supervisor paused: clarification needed on business category for {client_name}."],
        }

    discovered = state.get("discovered_sources", {})
    inspected = state.get("inspected_sources", {})
    topic_evidences = state.get("topic_evidences", [])

    # Honest Zero-Sources Reporting: If search returned zero sources, do not fabricate findings
    if not discovered and not topic_evidences:
        exec_summary = "Zero sources retrieved: No verifiable market evidence could be retrieved across the queried terms."
        synthesis = MarketResearchSynthesisOutput(
            executive_summary=exec_summary,
            key_findings=[
                CitedKeyFinding(
                    finding="Zero sources retrieved: No verifiable evidence was found across the queried terms.",
                    source_url=None,
                )
            ],
            observed_competitors=[],
            inferred_opportunities=[],
            research_dimensions=[],
            search_limitations="No search results were returned by the search engine for the requested query parameters.",
        )
        return {
            "synthesis": synthesis,
            "final_report": exec_summary,
            "activity_logs": ["Zero sources retrieved: honest fallback activated."],
        }

    if on_event:
        try:
            await on_event({
                "type": "status",
                "stage": "synthesizing",
                "message": f"Lead Research Editor: Compiling publication-grade report from {len(topic_evidences)} topic dossiers...",
            })
        except Exception:
            pass

    # Format multi-topic evidence dossiers
    evidence_blocks: list[str] = []
    for ev in topic_evidences:
        clean_excerpts = [ex for ex in ev.key_excerpts if is_substantive_content_line(ex)]
        exc_str = "\n".join(f"      * Verbatim Excerpt: \"{ex}\"" for ex in clean_excerpts) if clean_excerpts else "      * No standalone verbatim excerpts detected."
        met_str = ", ".join(ev.detected_metrics) if ev.detected_metrics else "None"
        evidence_blocks.append(
            f"### Facet: {ev.topic_title} (Target: {ev.target_entity or 'General'}, Status: {ev.status})\n"
            f"  - Core Finding: {ev.summary}\n"
            f"  - Verified Metrics / Numbers: {met_str}\n"
            f"  - Verbatim Evidence Excerpts:\n{exc_str}"
        )
    evidence_text = "\n\n".join(evidence_blocks) if evidence_blocks else "Zero topic dossiers gathered."

    # Format discovered source bibliography
    clean_sources: list[str] = []
    for url, d in list(discovered.items())[:15]:
        content = d.get("content") or d.get("snippet", "")
        clean_desc = content[:220].replace("\n", " ").strip()
        clean_sources.append(f"- [{d.get('title', 'Source')}]({url}): {clean_desc}")
    sources_text = "\n".join(clean_sources) if clean_sources else "Zero sources discovered."

    mode_str = state.get("research_mode", "client_scoped")
    if plan and getattr(plan, "research_mode", None):
        mode_str = plan.research_mode.value if hasattr(plan.research_mode, "value") else str(plan.research_mode)

    client_name = (context.client_name if context else None) or "the client brand"

    if mode_str == "independent_research":
        scope_directive = """--- RESEARCH SCOPE: STRICTLY INDEPENDENT MARKET RESEARCH ---
STRICT ISOLATION CONTRACT:
1. This is an INDEPENDENT market investigation into the requested external entities / brands.
2. Do NOT mention, reference, or relate this research to any agency client (e.g. do NOT mention Hotel Shauryawada, Handewadi, restaurants, or dining).
3. The entities being investigated (e.g. Blue Tokai, Subko, Third Wave Coffee) are competing directly against EACH OTHER in their market. Their competitor_type is 'direct'. They are NOT indirect competitors to a restaurant!
4. Strategic whitespace opportunities must be opportunities within the investigated market itself (e.g. specialty coffee roasters), NOT recommendations for an external restaurant client!
5. Never invent or force an external client relationship."""
        rule_5 = "5. Inferred opportunities must be categorized as 'hypothesis' by default, representing whitespace within the investigated market itself (do NOT relate to any agency client), with concrete 'missing_evidence', a practical low-risk 'test_method', and measurable 'validation_criteria'."
    elif mode_str == "client_informed_external":
        brand_block = _format_brand_context_block(context, query)
        brand_section = f"\n{brand_block}\n" if brand_block else ""
        scope_directive = f"""--- RESEARCH SCOPE: CLIENT-INFORMED EXTERNAL OPPORTUNITY ANALYSIS ---
{brand_section}
STRICT SCOPE CONTRACT:
1. Synthesize the external market research (e.g. specialty coffee trends, retail models, subscription practices).
2. Directly evaluate how the active client brand ({client_name}) can realistically explore, adapt, or adopt these external findings.
3. Inferred opportunities should explicitly identify concrete, low-risk opportunities for {client_name} based on the external research."""
        rule_5 = f"5. Inferred opportunities must be categorized as 'hypothesis' by default, evaluating actionable ways {client_name} could realistically adopt or test these external practices, with concrete 'missing_evidence', a practical low-risk 'test_method', and measurable 'validation_criteria'."
    else:  # client_scoped
        brand_block = _format_brand_context_block(context, query)
        brand_section = f"\n{brand_block}\n" if brand_block else ""
        scope_directive = f"""--- RESEARCH SCOPE: CLIENT-SCOPED COMPETITIVE INTELLIGENCE ---
{brand_section}
STRICT SCOPE CONTRACT:
1. Anchor all findings, competitor observations, and whitespace opportunities to the active client brand ({client_name})."""
        rule_5 = f"5. Inferred opportunities must be categorized as 'hypothesis' by default, contrasting competitor findings against {client_name}'s category and market, with concrete 'missing_evidence', a practical low-risk 'test_method', and measurable 'validation_criteria'."

    synthesis_prompt = f"""You are the Lead Market Research Editor for AgencyOS.
Produce an evidence-grounded research synthesis for the user query based on the multi-topic investigation dossiers below.

{scope_directive}

USER QUERY: "{query}"

--- MULTI-TOPIC RESEARCH EVIDENCE DOSSIERS ---
{evidence_text}

--- RETRIEVED SOURCES BIBLIOGRAPHY ---
{sources_text}

STRICT EDITORIAL RULES:
1. Every competitor (observed_competitors) MUST be an actual business, brand, company, or product. Output exact entity name (e.g. 'Blue Tokai', 'Subko', 'Third Wave Coffee', 'Garden Gate', 'Surve\\'s'). Never output SEO aggregate titles or listicle names (e.g. never 'Restaurants listed on Zomato', 'Top 10 Cafes', 'Casual Dining in Pune').
2. Every competitor MUST cite a supporting_source_url that appears verbatim in the bibliography above.
3. Quantifiable claims (pricing tiers, subscription fees, promotional discounts) must be grounded in the verified metrics and excerpts.
4. For research_dimensions, explicitly account for each requested query dimension:
   - 'answered': verified by inspected primary page content.
   - 'partial': partially supported by search snippet only.
   - 'not_verified': dimension was researched, but sufficient evidence was not found.
   - 'not_available': information is not publicly published or accessible.
   - 'missing': dimension was not reached within tool budget.
{rule_5}
6. When customer complaints are noted, report whether it is an individual anecdote (1 review) or a recurring complaint (multiple verified reviews).
7. Output valid JSON strictly matching the MarketResearchSynthesisOutput schema."""

    try:
        synthesis = await invoke_structured_llm(
            prompt=synthesis_prompt,
            schema_class=MarketResearchSynthesisOutput,
            model=settings.MARKET_RESEARCH_MODEL,
            temperature=0.1,
        )
    except Exception as exc:
        logger.error(f"[compile_report_node] Synthesis LLM failed: {exc}", exc_info=True)
        findings: list[CitedKeyFinding] = []
        for ev in topic_evidences:
            for f in ev.findings[:2]:
                url = ev.inspected_sources[0] if ev.inspected_sources else (ev.snippet_sources[0] if ev.snippet_sources else None)
                if is_substantive_content_line(f):
                    findings.append(CitedKeyFinding(finding=f, source_url=url))
        if not findings:
            findings.append(CitedKeyFinding(finding=f"Market landscape investigation data retrieved across {len(discovered)} discovered sources.", source_url=None))

        fallback_competitors: list[CompetitorFindingItem] = []
        for ev in topic_evidences:
            if ev.target_entity:
                url = ev.inspected_sources[0] if ev.inspected_sources else (ev.snippet_sources[0] if ev.snippet_sources else None)
                fallback_competitors.append(
                    CompetitorFindingItem(
                        competitor_name=ev.target_entity,
                        platform="web",
                        primary_hook=ev.summary[:150] if ev.summary else "Competitor operating in target market.",
                        supporting_source_url=url,
                    )
                )

        synthesis = MarketResearchSynthesisOutput(
            executive_summary=f"Deep research completed across {len(discovered)} sources ({len(inspected)} deeply inspected). Synthesis compiled from topic dossiers.",
            key_findings=findings[:5],
            observed_competitors=fallback_competitors[:4],
            inferred_opportunities=[],
            research_dimensions=[],
            search_limitations=f"Synthesis generated from topic dossiers: {exc}",
        )

    # -----------------------------------------------------------------------
    # Deterministic Post-Validation Passes
    # -----------------------------------------------------------------------
    all_inspected_metrics: set[str] = set()
    all_inspected_text = ""
    for ev in topic_evidences:
        for m in ev.detected_metrics:
            all_inspected_metrics.add(m.strip().lower())
        for ex in ev.key_excerpts:
            all_inspected_text += " " + ex.lower()
    for p in inspected.values():
        all_inspected_text += " " + str(p.get("summary", "")).lower()

    # Pass 1: Competitor Classification & Relevance (Channel platforms vs Direct competitors)
    AGGREGATOR_PLATFORMS = {
        "zomato", "swiggy", "uber eats", "ubereats", "doordash", "deliveroo",
        "grubhub", "tripadvisor", "booking.com", "booking", "airbnb", "expedia",
        "magicpin", "eazydiner", "dineout", "justdial"
    }
    cleaned_competitors: list[CompetitorFindingItem] = []
    for comp in synthesis.observed_competitors:
        c_name_lower = comp.competitor_name.lower().strip()
        # Filter out generic listicle article titles
        if re.search(r"^\d+\s+(?:gorgeous|best|top|popular|great)\b", c_name_lower):
            continue
        if re.search(r"\b(?:list of|top \d+|best restaurants|casual dining in)\b", c_name_lower):
            continue

        if any(agg in c_name_lower for agg in AGGREGATOR_PLATFORMS):
            comp.competitor_type = CompetitorType.CHANNEL
            if "zomato" in c_name_lower:
                comp.competitor_name = "Zomato"
            elif "swiggy" in c_name_lower:
                comp.competitor_name = "Swiggy"
            elif "magicpin" in c_name_lower:
                comp.competitor_name = "Magicpin"
            if not comp.relevance:
                comp.relevance = CompetitorRelevance(
                    geographic_overlap="National / Regional delivery coverage",
                    product_or_service_overlap="Food delivery aggregator & restaurant discovery channel platform, not a direct culinary competitor",
                    price_overlap="Platform commission & delivery fees",
                    audience_overlap="Online ordering diners",
                    occasion_overlap="Home delivery & table reservations",
                )
            else:
                comp.relevance.product_or_service_overlap = "Delivery & discovery channel platform, not a direct culinary producer"
        else:
            if mode_str == "independent_research":
                comp.competitor_type = CompetitorType.DIRECT
                if not comp.relevance:
                    comp.relevance = CompetitorRelevance(
                        geographic_overlap="Operating in target regional market",
                        product_or_service_overlap="Direct competition in core category and offerings",
                        price_overlap="Direct category price tier",
                        audience_overlap="Target consumer segment",
                        occasion_overlap="Core consumption occasion",
                    )
            elif not getattr(comp, "competitor_type", None):
                comp.competitor_type = CompetitorType.DIRECT

        cleaned_competitors.append(comp)
    synthesis.observed_competitors = cleaned_competitors

    # Mode-specific scrubbing for INDEPENDENT_RESEARCH
    if mode_str == "independent_research" and context and context.client_name:
        cname = context.client_name.strip()
        cname_pat = rf"\b(?:Hotel\s+)?{re.escape(cname)}(?:'s)?\b"
        synthesis.executive_summary = re.sub(
            rf"\s*While these entities operate in [^.]+? rather than direct restaurant competition with [^.]+?\.\s*",
            " ",
            synthesis.executive_summary,
            flags=re.IGNORECASE,
        )
        synthesis.executive_summary = re.sub(cname_pat, "specialty operators", synthesis.executive_summary, flags=re.IGNORECASE)
        for opp in synthesis.inferred_opportunities:
            opp.opportunity_description = re.sub(cname_pat, "Specialty operators", opp.opportunity_description, flags=re.IGNORECASE)
            opp.target_whitespace = re.sub(cname_pat, "specialty market", opp.target_whitespace, flags=re.IGNORECASE)

    # Pass 2: Review Integrity Check (Complaints Scope: 1 anecdote vs 2-4 signal vs 5+ recurring)
    for kf in synthesis.key_findings:
        text_lower = kf.finding.lower()
        if any(w in text_lower for w in ("complaint", "negative review", "delay", "freshness issue", "dissatisfaction")):
            has_multiple_reviews = bool(re.search(r"\b(?:multiple|\d{2,}|several|many|5\+|recurring)\s+(?:reviews|complaints|users)\b", text_lower))
            has_repeated = bool(re.search(r"\b(?:2|3|4|few|some|pair of)\s+(?:reviews|complaints|users)\b", text_lower))
            if has_multiple_reviews:
                if not kf.finding.startswith("Recurring customer complaint"):
                    kf.finding = f"Recurring customer complaint (multiple verified reviews): {re.sub(r'^(?:\[.*?\]\s*)+', '', kf.finding)}"
            elif has_repeated:
                if not kf.finding.startswith("Repeated customer signal"):
                    kf.finding = f"Repeated customer signal (2-4 reviews): {re.sub(r'^(?:\[.*?\]\s*)+', '', kf.finding)}"
            else:
                if not kf.finding.startswith("Preliminary individual anecdote") and not kf.finding.startswith("Repeated customer signal") and not kf.finding.startswith("Recurring customer complaint"):
                    kf.finding = f"Preliminary individual anecdote (1 review): {re.sub(r'^(?:\[.*?\]\s*)+', '', kf.finding)}"

    # Pass 3: Numerical Metric Verification
    for kf in synthesis.key_findings:
        has_num_metric = bool(re.search(r"(?:₹|\$|rs\.?|inr)\s*\d+|\b\d+(?:,\d+)?\s*(?:daily|lakh|crore|outlets|cafes|branches|stores|raans|orders)\b", kf.finding, re.IGNORECASE))
        if has_num_metric:
            numbers_in_finding = re.findall(r"\b\d+(?:[.,]\d+)?\b", kf.finding)
            matched_in_inspected = any(num in all_inspected_text or any(num in m for m in all_inspected_metrics) for num in numbers_in_finding)
            if not matched_in_inspected:
                all_discovered_text = " ".join((d.get("content") or d.get("snippet", "")) for d in discovered.values()).lower()
                matched_in_snippets = any(num in all_discovered_text for num in numbers_in_finding)
                if matched_in_snippets:
                    if not kf.finding.startswith("[PRELIMINARY"):
                        kf.finding = f"[PRELIMINARY SNIPPET - UNVERIFIED METRIC] {kf.finding}"
                else:
                    if not kf.finding.startswith("[Unverified Metric"):
                        kf.finding = f"[Unverified Metric / Estimate] {kf.finding}"

    # Pass 4: Strategic Recommendation Discipline
    for opp in synthesis.inferred_opportunities:
        if not getattr(opp, "status", None) or opp.status == OpportunityStatus.VALIDATED_OPPORTUNITY:
            has_inspected_support = any(
                any(u in ev.inspected_sources for u in opp.supporting_source_urls)
                for ev in topic_evidences
            )
            if not has_inspected_support:
                opp.status = OpportunityStatus.HYPOTHESIS
        if not opp.missing_evidence:
            opp.missing_evidence = ["Unit economics & food cost margins", "Customer willingness-to-pay threshold", "Kitchen prep and dispatch capacity"]
        if not opp.test_method:
            opp.test_method = "Run a 7-day social story poll or limited 20-order weekend pre-order test"
        if not opp.validation_criteria:
            opp.validation_criteria = "Achieve >= 15 pre-orders or >= 65% positive response rate before rollout"

    # Pass 5: Dimension Statuses Accounting & Honest Demotion
    for dim in synthesis.research_dimensions:
        s_val = dim.status.value if hasattr(dim.status, "value") else str(dim.status).lower()
        negative_summary_cues = (
            "not distinctly extracted", "not extracted", "not verified", "not found",
            "not available", "not analyzed", "unverified", "no direct", "sparse",
            "could not be", "not present", "missing", "not quantified", "sparsely",
            "no review", "noise metrics", "cannot be confirmed", "not clearly interpretable",
            "not distinctly", "not extracted in"
        )
        if any(neg in dim.summary.lower() for neg in negative_summary_cues):
            if "not available" in dim.summary.lower() or "not public" in dim.summary.lower():
                dim.status = ResearchDimensionStatus.NOT_AVAILABLE
            else:
                dim.status = ResearchDimensionStatus.NOT_VERIFIED
        elif s_val in ("answered", "verified"):
            dim.status = ResearchDimensionStatus.ANSWERED
        elif s_val in ("partial", "partially_answered"):
            dim.status = ResearchDimensionStatus.PARTIAL
        elif s_val in ("not_verified", "unverified"):
            dim.status = ResearchDimensionStatus.NOT_VERIFIED
        elif s_val in ("not_available", "unavailable"):
            dim.status = ResearchDimensionStatus.NOT_AVAILABLE
        else:
            dim.status = ResearchDimensionStatus.MISSING

    log_msg = f"Editorial Compiler finished: {len(synthesis.key_findings)} key findings, {len(synthesis.observed_competitors)} competitors, {len(synthesis.research_dimensions)} dimensions tracked."
    return {
        "synthesis": synthesis,
        "final_report": synthesis.executive_summary,
        "activity_logs": [log_msg],
    }


