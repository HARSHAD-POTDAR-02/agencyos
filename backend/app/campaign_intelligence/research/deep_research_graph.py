def route_topics(state: DeepResearchState) -> Literal["topic_worker", "compile_report"]:
    """Determines whether to investigate the next sub-topic or transition to final report compilation."""
    plan = state["plan"]
    idx = state["current_topic_idx"]
    used = state["used_tool_budget"]
    limit = state["max_global_budget"]

    if plan and idx < len(plan.sub_topics) and used < limit:
        return "topic_worker"
    return "compile_report"


