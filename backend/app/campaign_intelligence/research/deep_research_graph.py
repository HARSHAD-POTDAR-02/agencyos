async def compile_report_node(state: DeepResearchState) -> dict[str, Any]:
    """
    Synthesizes the multi-topic evidence dossiers into a publication-grade intelligence report.
    Grounds all competitor observations, pricing claims, and whitespace opportunities
    in the verified evidence dossiers.
    """
    query = state["query"]
    on_event = state.get("on_event_fn")
    
    if on_event:
        try:
            await on_event({
                "type": "status",
                "stage": "synthesizing",
                "message": f"Lead Research Editor: Compiling publication-grade report from {len(state.get('topic_evidences', []))} topic dossiers...",
            })
        except Exception:
            pass

    discovered = state.get("discovered_sources", {})
    inspected = state.get("inspected_sources", {})
    topic_evidences = state.get("topic_evidences", [])

    # Format multi-topic evidence dossiers
    evidence_blocks: list[str] = []
    for ev in topic_evidences:
        clean_excerpts = [ex for ex in ev.key_excerpts if is_substantive_content_line(ex)]
        exc_str = "\n".join(f"      * Verbatim Excerpt: \"{ex}\"" for ex in clean_excerpts) if clean_excerpts else "      * No standalone verbatim excerpts detected."
        met_str = ", ".join(ev.detected_metrics) if ev.detected_metrics else "None"
        evidence_blocks.append(
            f"### Facet: {ev.topic_title} (Target: {ev.target_entity or 'General'}, Status: {ev.status})\n"
            f"  - Core Finding: {ev.summary}\n"
            f"  - Verified Metrics / Numbers: {met_str}\n"
            f"  - Verbatim Evidence Excerpts:\n{exc_str}"
        )
    evidence_text = "\n\n".join(evidence_blocks) if evidence_blocks else "Zero topic dossiers gathered."

    # Format discovered source bibliography (cleaning snippets and navigation tags)
    clean_sources: list[str] = []
    for url, d in list(discovered.items())[:15]:
        content = d.get("content") or d.get("snippet", "")
        clean_desc = content[:220].replace("\n", " ").strip()
        clean_sources.append(f"- [{d.get('title', 'Source')}]({url}): {clean_desc}")
    sources_text = "\n".join(clean_sources) if clean_sources else "Zero sources discovered."

    context = state.get("context")
    brand_block = _format_brand_context_block(context, query)
    brand_section = f"\n{brand_block}\n" if brand_block else ""

    synthesis_prompt = f"""You are the Lead Market Research Editor for AgencyOS.
Produce an evidence-grounded research synthesis for the user query based on the multi-topic investigation dossiers below.
{brand_section}
USER QUERY: "{query}"

--- MULTI-TOPIC RESEARCH EVIDENCE DOSSIERS ---
{evidence_text}

--- RETRIEVED SOURCES BIBLIOGRAPHY ---
{sources_text}

STRICT EDITORIAL RULES:
1. Every competitor (observed_competitors) MUST be an actual business, brand, company, or product. Output exact entity name (e.g. 'Blue Tokai', 'Subko', 'Third Wave Coffee', 'Surve\\'s', 'Jagdamb'). Never output SEO aggregate titles or listicle names.
2. Every competitor MUST cite a supporting_source_url that appears verbatim in the bibliography above.
3. Quantifiable claims (pricing tiers, subscription fees, promotional discounts) must be grounded in the verified metrics and excerpts.
4. For research_dimensions, explicitly account for each requested query dimension (answered, partial, or missing).
5. When synthesizing strategic market whitespace and inferred opportunities, directly contrast competitor findings against the active client brand's category, positioning, and operating market.
6. Output valid JSON strictly matching the MarketResearchSynthesisOutput schema."""

    try:
        synthesis = await invoke_structured_llm(
            prompt=synthesis_prompt,
            schema_class=MarketResearchSynthesisOutput,
            model=settings.MARKET_RESEARCH_MODEL,
            temperature=0.1,
        )
    except Exception as exc:
        logger.error(f"[compile_report_node] Synthesis LLM failed: {exc}", exc_info=True)
        from app.campaign_intelligence.specialists.market_research_adapter import (
            CitedKeyFinding,
            CompetitorFindingItem,
        )
        findings: list[CitedKeyFinding] = []
        for ev in topic_evidences:
            for f in ev.findings[:2]:
                url = ev.inspected_sources[0] if ev.inspected_sources else (ev.snippet_sources[0] if ev.snippet_sources else None)
                if is_substantive_content_line(f):
                    findings.append(CitedKeyFinding(finding=f, source_url=url))
        if not findings:
            findings.append(CitedKeyFinding(finding=f"Market landscape investigation data retrieved across {len(discovered)} discovered sources.", source_url=None))

        fallback_competitors: list[CompetitorFindingItem] = []
        for ev in topic_evidences:
            if ev.target_entity:
                url = ev.inspected_sources[0] if ev.inspected_sources else (ev.snippet_sources[0] if ev.snippet_sources else None)
                fallback_competitors.append(
                    CompetitorFindingItem(
                        competitor_name=ev.target_entity,
                        platform="web",
                        primary_hook=ev.summary[:150] if ev.summary else "Competitor operating in target market.",
                        supporting_source_url=url,
                    )
                )

        synthesis = MarketResearchSynthesisOutput(
            executive_summary=f"Deep research completed across {len(discovered)} sources ({len(inspected)} deeply inspected). Synthesis compiled from topic dossiers.",
            key_findings=findings[:5],
            observed_competitors=fallback_competitors[:4],
            inferred_opportunities=[],
            research_dimensions=[],
            search_limitations=f"Synthesis generated from topic dossiers: {exc}",
        )

    log_msg = f"Editorial Compiler finished: {len(synthesis.key_findings)} key findings, {len(synthesis.observed_competitors)} competitors, {len(synthesis.research_dimensions)} dimensions tracked."
    return {
        "synthesis": synthesis,
        "final_report": synthesis.executive_summary,
        "activity_logs": [log_msg],
    }


