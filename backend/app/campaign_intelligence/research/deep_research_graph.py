def build_deep_research_graph():
    """Compiles the 3-stage LangGraph Deep Research workflow."""
    workflow = StateGraph(DeepResearchState)
    workflow.add_node("plan_scoping", plan_scoping_node)
    workflow.add_node("topic_worker", topic_worker_node)
    workflow.add_node("compile_report", compile_report_node)

    workflow.add_edge(START, "plan_scoping")
    workflow.add_conditional_edges("plan_scoping", route_topics)
    workflow.add_conditional_edges("topic_worker", route_topics)
    workflow.add_edge("compile_report", END)

    return workflow.compile()


def _map_platform(platform_str: str) -> SocialPlatform:
    lower = (platform_str or "").lower()
    for sp in SocialPlatform:
        if sp.value in lower:
            return sp
    return SocialPlatform.instagram


async def run_deep_research(
    query: str,
    context: CampaignStudioContext,
    max_global_budget: int = 6,
    on_event: Any | None = None,
) -> SpecialistResult:
    """
    Main orchestration entry point for deep multi-stage competitive market research.
    Executes the LangGraph Deep Research workflow and returns a formatted SpecialistResult.
    """
    graph = build_deep_research_graph()

    initial_state: DeepResearchState = {
        "query": query,
        "context": context,
        "plan": None,
        "current_topic_idx": 0,
        "used_tool_budget": 0,
        "max_global_budget": max_global_budget,
        "topic_evidences": [],
        "discovered_sources": {},
        "inspected_sources": {},
        "synthesis": None,
        "final_report": "",
        "activity_logs": [],
        "on_event_fn": on_event,
        "research_mode": "client_scoped",
        "is_ambiguous": False,
    }

    t0 = time.perf_counter()
    final_output = await graph.ainvoke(initial_state)
    duration = time.perf_counter() - t0

    synthesis: MarketResearchSynthesisOutput | None = final_output.get("synthesis")
    activity_logs: list[str] = final_output.get("activity_logs", [])
    discovered = final_output.get("discovered_sources", {})
    inspected = final_output.get("inspected_sources", {})

    if not synthesis:
        synthesis = MarketResearchSynthesisOutput(
            executive_summary=final_output.get("final_report") or "Deep research concluded with preliminary findings.",
            key_findings=[CitedKeyFinding(finding="Preliminary market landscape findings collected.", source_url=None)],
            observed_competitors=[],
            inferred_opportunities=[],
            research_dimensions=[],
            search_limitations="Synthesis compilation incomplete or partial evidence collected.",
        )

    # Map validated competitors into CompetitorActivity domain model
    competitor_activities: list[CompetitorActivity] = []
    for c in synthesis.observed_competitors:
        src_url = c.supporting_source_url or "https://agencyos.local"
        if not (src_url.startswith("http://") or src_url.startswith("https://")):
            src_url = "https://agencyos.local"
        netloc = urlparse(src_url).netloc or "Web Search"
        citation = EvidenceCitation(
            source_title=c.competitor_name or "Competitor Observation",
            source_url=src_url,
            publisher=netloc,
            excerpt=c.citation_quote or c.observed_creative_angle or "Observed competitor strategy",
            is_direct_quote=bool(c.citation_quote),
        )
        competitor_activities.append(
            CompetitorActivity(
                competitor_name=c.competitor_name,
                platform=_map_platform(c.platform),
                observed_creative_angle=c.observed_creative_angle,
                observed_format=c.observed_format,
                citation=citation,
                competitor_type=getattr(c, "competitor_type", CompetitorType.DIRECT),
                relevance=getattr(c, "relevance", None),
            )
        )

    # Map validated opportunities
    inferred_opportunities: list[InferredOpportunity] = []
    for o in synthesis.inferred_opportunities:
        cites: list[EvidenceCitation] = []
        for u in o.supporting_source_urls:
            if u.startswith("http://") or u.startswith("https://"):
                netloc = urlparse(u).netloc or "Web Source"
                cites.append(
                    EvidenceCitation(
                        source_title=f"Supporting Evidence ({netloc})",
                        source_url=u,
                        publisher=netloc,
                        excerpt="Verified market evidence supporting this whitespace opportunity.",
                        is_direct_quote=False,
                    )
                )
        inferred_opportunities.append(
            InferredOpportunity(
                opportunity_description=o.opportunity_description,
                target_whitespace=o.target_whitespace,
                supporting_citations=cites,
                status=getattr(o, "status", OpportunityStatus.HYPOTHESIS),
                supporting_evidence=getattr(o, "supporting_evidence", []),
                missing_evidence=getattr(o, "missing_evidence", []),
                test_method=getattr(o, "test_method", None),
                validation_criteria=getattr(o, "validation_criteria", None),
            )
        )

    # Format supporting evidence citations
    supporting_citations: list[EvidenceCitation] = []
    for url, p in inspected.items():
        if url.startswith("http://") or url.startswith("https://"):
            netloc = urlparse(url).netloc or "Inspected Webpage"
            supporting_citations.append(
                EvidenceCitation(
                    source_title=p.get("title") or netloc or "Inspected Source",
                    source_url=url,
                    publisher=netloc,
                    excerpt=p.get("summary") or "Inspected page content",
                    is_direct_quote=False,
                )
            )

    if not supporting_citations:
        for url, d in discovered.items():
            if url.startswith("http://") or url.startswith("https://"):
                netloc = urlparse(url).netloc or "Search Snippet"
                supporting_citations.append(
                    EvidenceCitation(
                        source_title=d.get("title") or netloc or "Search Result",
                        source_url=url,
                        publisher=netloc,
                        excerpt=d.get("snippet") or "Search snippet",
                        is_direct_quote=False,
                    )
                )

    artifact_payload = MarketResearchArtifactPayload(
        query_topic=query or "Deep Market Landscape & Competitive Intelligence",
        observed_competitors=competitor_activities,
        inferred_opportunities=inferred_opportunities,
        verified_sources=supporting_citations,
        search_limitations=synthesis.search_limitations,
        research_dimensions=synthesis.research_dimensions,
        discovered_count=len(discovered),
        inspected_count=len(inspected),
        claim_supported_count=len(competitor_activities) + len(inferred_opportunities),
    )

    # Format Markdown Reply
    reply_lines = [
        f"**Deep Research Report**: {synthesis.executive_summary}\n",
        "### Key Findings",
    ]
    for kf in synthesis.key_findings:
        cite = f" \\[[source]({kf.source_url})\\]" if kf.source_url else ""
        reply_lines.append(f"- {kf.finding}{cite}")

    if synthesis.research_dimensions:
        reply_lines.append("\n### Research Scope & Dimension Tracking")
        status_badges = {
            ResearchDimensionStatus.ANSWERED: ("✅", "Verified"),
            ResearchDimensionStatus.PARTIAL: ("⚠️", "Partial"),
            ResearchDimensionStatus.NOT_VERIFIED: ("🔍", "Not Verified"),
            ResearchDimensionStatus.NOT_AVAILABLE: ("🚫", "Not Available"),
            ResearchDimensionStatus.MISSING: ("❌", "Missing"),
        }
        for d in synthesis.research_dimensions:
            icon, label = status_badges.get(d.status, ("ℹ️", str(d.status).capitalize()))
            reply_lines.append(f"- {icon} **{d.dimension}**: {label} — {d.summary}")

    if competitor_activities:
        reply_lines.append("\n### Observed Competitor Landscape")
        for c in competitor_activities:
            type_tag = f"[{c.competitor_type.value.upper()}] " if hasattr(c, "competitor_type") else ""
            rel_parts = []
            if hasattr(c, "relevance") and c.relevance:
                if getattr(c.relevance, "geographic_overlap", None):
                    rel_parts.append(f"Geo: {c.relevance.geographic_overlap}")
                if getattr(c.relevance, "product_or_service_overlap", None):
                    rel_parts.append(f"Product: {c.relevance.product_or_service_overlap}")
            rel_str = f" *({', '.join(rel_parts)})*" if rel_parts else ""
            cite_label = (c.citation.publisher or c.citation.source_title) if c.citation else "Source"
            cite_str = f" — *[{cite_label}]({c.citation.source_url})*" if c.citation else ""
            reply_lines.append(f"- {type_tag}**{c.competitor_name}** ({c.platform.value}): {c.observed_creative_angle}{rel_str}{cite_str}")

    if inferred_opportunities:
        reply_lines.append("\n### Strategic Market Whitespace & Actionable Hypotheses")
        for opp in inferred_opportunities:
            status_tag = f"[{opp.status.value.replace('_', ' ').upper()}] " if hasattr(opp, "status") else "[HYPOTHESIS] "
            extra_lines = []
            if getattr(opp, "missing_evidence", None):
                extra_lines.append(f"    * Missing Evidence: {', '.join(opp.missing_evidence)}")
            if getattr(opp, "test_method", None):
                extra_lines.append(f"    * Low-Risk Test: {opp.test_method}")
            if getattr(opp, "validation_criteria", None):
                extra_lines.append(f"    * Success Metric: {opp.validation_criteria}")
            extra_str = ("\n" + "\n".join(extra_lines)) if extra_lines else ""
            reply_lines.append(f"- {status_tag}**{opp.opportunity_description}** *(Whitespace: {opp.target_whitespace})*{extra_str}")

    if synthesis.search_limitations:
        reply_lines.append(f"\n> ⚠️ **Research Limitations**: {synthesis.search_limitations}")

    search_only_count = max(0, len(discovered) - len(inspected))
    reply_lines.append(
        f"\n**Sources Consulted**: {len(discovered)} discovered search results "
        f"({len(inspected)} deeply inspected pages, {search_only_count} search snippets only, {len(competitor_activities) + len(inferred_opportunities)} claims supported)."
    )

    return SpecialistResult(
        specialist_id="market_research",
        specialist_name="Deep Research Analyst",
        reply="\n".join(reply_lines).strip(),
        artifact_type=ArtifactType.research_evidence,
        artifact_payload=artifact_payload.model_dump(),
        activity_logs=activity_logs,
        suggested_followups=synthesis.suggested_followups or [],
    )
