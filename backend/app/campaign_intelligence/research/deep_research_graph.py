async def plan_scoping_node(state: DeepResearchState) -> dict[str, Any]:
    """
    Decomposes the complex user research query into 2 to 4 structured sub-topics.
    Guarantees client brand grounding, pre-flight evidence planning, and entity isolation.
    If the client business category is ambiguous for open-ended competitor questions, halts to clarify.
    """
    query = state["query"]
    context = state.get("context")
    on_event = state.get("on_event_fn")

    mode, is_ambiguous = _resolve_research_mode(query, context)

    # Ambiguity Gate: If business category is missing for open competitor questions, halt immediately
    if is_ambiguous:
        client_name = (context.client_name if context else None) or "the client brand"
        log_msg = f"Deep Research Supervisor: Pausing research because business category for '{client_name}' is missing. Clarification requested."
        if on_event:
            try:
                await on_event({"type": "turn_start", "message": log_msg})
            except Exception:
                pass
        plan = DeepResearchPlan(
            plan_summary=f"Clarification required: Business category for '{client_name}' is not specified in workspace context.",
            sub_topics=[],
            is_ambiguous_clarification=True,
            research_mode=mode,
        )
        return {
            "plan": plan,
            "current_topic_idx": 0,
            "research_mode": mode.value,
            "is_ambiguous": True,
            "activity_logs": [log_msg],
        }

    if on_event:
        try:
            await on_event({
                "type": "status",
                "stage": "planning",
                "message": f"Deep Research Supervisor [{mode.value.upper()}]: Decomposing research query into structured investigation facets...",
            })
        except Exception:
            pass

    prior_context_block = _build_deep_research_prior_context(context, query, mode)

    if mode == ResearchScopeMode.INDEPENDENT_RESEARCH:
        scope_directive = (
            "--- RESEARCH SCOPE: INDEPENDENT MARKET RESEARCH ---\n"
            "The user is investigating an independent market or explicitly named entities.\n"
            "STRICT ISOLATION: Do NOT inject, assume, or constrain findings to any external agency client or client location context.\n"
            "Investigate exclusively the brands, categories, and locations explicitly specified in the user query."
        )
    elif mode == ResearchScopeMode.CLIENT_INFORMED_EXTERNAL:
        brand_block = _format_brand_context_block(context, query)
        scope_directive = (
            "--- RESEARCH SCOPE: CLIENT-INFORMED EXTERNAL TRENDS ---\n"
            f"{brand_block}\n"
            "Research external industry trends, content formats, and viral hooks using the active client's industry and audience as context."
        )
    else:  # CLIENT_SCOPED
        brand_block = _format_brand_context_block(context, query)
        scope_directive = (
            "--- RESEARCH SCOPE: CLIENT-SCOPED COMPETITIVE INTELLIGENCE ---\n"
            f"{brand_block}\n"
            "Anchor research exclusively to the active client brand and its operating industry/geography."
        )

    plan_prompt = f"""You are the Deep Research Supervisor for AgencyOS Campaign Intelligence.
Analyze the user research query and decompose it into 2 to 4 structured sub-investigation facets.

{scope_directive}
{prior_context_block}

USER QUERY: "{query}"

MANDATORY PLANNING RULES:
1. CLIENT BRAND ANCHORING: If research scope is CLIENT_SCOPED, anchor the entire investigation specifically to the ACTIVE CLIENT BRAND.
2. ENTITY ISOLATION: If specific competitor companies, brands, or products are named in the query (e.g. 'Blue Tokai', 'Subko', 'Third Wave Coffee'), allocate at least one dedicated sub-topic to EACH named competitor entity. Do NOT bundle all competitors into a single generic search.
3. PRE-FLIGHT EVIDENCE PLANNING (MANDATORY): Map each sub-topic to the correct evidence_type:
   - 'official_menu_or_store': For product pricing, menus, retail packs, subscription plans.
   - 'independent_reviews': For customer complaints, negative feedback, delivery delays, freshness issues. (Must target review platforms/forums, NOT brand homepages).
   - 'directory_or_outlets': For retail footprint, branch count, store locations.
   - 'press_and_positioning': For social content, marketing angles, brand positioning, press coverage.
4. DIMENSION ACCOUNTING: Ensure specific requested dimensions (pricing tiers, subscription models, seasonal gift bundles, customer review complaints) are explicitly captured in research_questions.
5. BUDGET ALLOCATION: Allocate 1 or 2 tool calls per sub-topic. Total tool calls across all sub-topics must not exceed {state.get('max_global_budget', 6)}.
6. SEARCH QUERY PRECISION: Provide specific, keyword-rich search queries. For 'independent_reviews', queries MUST target reviews, complaints, or forums (e.g. 'brand reviews complaints delay'). For 'official_menu_or_store', queries MUST target official store or menu pages."""

    try:
        plan = await invoke_structured_llm(
            prompt=plan_prompt,
            schema_class=DeepResearchPlan,
            model=settings.MARKET_RESEARCH_MODEL,
            temperature=0.1,
        )
        plan.research_mode = mode
    except Exception as e:
        logger.warning(f"Structured plan generation failed ({e}); using heuristic fallback plan.")
        client_name = context.client_name if context else "Client Brand"
        industry = context.client_industry if context else "Industry"
        plan = DeepResearchPlan(
            plan_summary=f"Default faceted research plan targeting competitive landscape and market whitespace for {client_name}.",
            research_mode=mode,
            sub_topics=[
                ResearchSubTopic(
                    topic_id="topic_direct_competitors",
                    title=f"Direct Competitors & Offerings ({industry})",
                    research_questions=["What are the verified competitor pricing tiers and core products?"],
                    suggested_queries=[f"{client_name} {industry} competitors pricing"],
                    max_tool_budget=2,
                    evidence_type="official_menu_or_store",
                ),
                ResearchSubTopic(
                    topic_id="topic_indirect_whitespace",
                    title="Customer Complaints & Whitespace",
                    research_questions=["What are recurring customer complaints or unmet pain points?"],
                    suggested_queries=[f"{client_name} {industry} reviews complaints issues"],
                    max_tool_budget=2,
                    evidence_type="independent_reviews",
                ),
            ],
        )

    topic_titles = [t.title for t in plan.sub_topics]
    log_msg = f"Deep Research Supervisor [{mode.value.upper()}] generated {len(plan.sub_topics)} investigation facets: {', '.join(topic_titles)}."
    
    if on_event:
        try:
            await on_event({"type": "turn_start", "message": log_msg})
        except Exception:
            pass

    return {
        "plan": plan,
        "current_topic_idx": 0,
        "research_mode": mode.value,
        "is_ambiguous": False,
        "activity_logs": [log_msg],
    }


