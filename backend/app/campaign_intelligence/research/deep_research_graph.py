def _format_brand_context_block(context: CampaignStudioContext | None, query: str) -> str:
    """Format the active studio client context for research supervisor and editorial synthesis."""
    if not context or not context.client_name:
        return ""
    
    client_name = context.client_name.strip()
    industry = (context.client_industry or "General Business").strip()
    location = (context.client_location or "").strip()
    brief = context.campaign_brief
    target_audience = brief.target_audience if (brief and brief.target_audience) else []
    brand_ctx = context.brand_context
    pillars = brand_ctx.content_pillars if (brand_ctx and brand_ctx.content_pillars) else []
    facts = brand_ctx.confirmed_facts if (brand_ctx and brand_ctx.confirmed_facts) else []

    facts_line = f"\n- Confirmed Brand Facts: {'; '.join(facts[:5])}" if facts else ""
    pillars_line = f"\n- Content Pillars / Focus: {', '.join(pillars[:4])}" if pillars else ""
    audience_line = f"\n- Target Audience: {', '.join(target_audience[:3])}" if target_audience else ""
    loc_line = f"\n- Operating Location: {location}" if location else ""

    return (
        f"--- ACTIVE CLIENT BRAND (CAMPAIGN STUDIO WORKSPACE) ---\n"
        f"- Brand Name: {client_name}\n"
        f"- Industry / Category: {industry}"
        f"{loc_line}"
        f"{audience_line}"
        f"{pillars_line}"
        f"{facts_line}\n\n"
        f"CRITICAL BRAND GROUNDING RULES:\n"
        f"1. When the user asks about 'our brand', 'our business', 'our restaurant', 'our competitors', 'we', 'us', "
        f"or asks open-ended questions like 'what are our direct and indirect competitors?' or 'who are our rivals?', "
        f"'our' refers EXCLUSIVELY to the active client brand: {client_name} ({industry}{f' in {location}' if location else ''}).\n"
        f"2. Never confuse 'our brand' with AgencyOS, software, or tech SaaS. AgencyOS is the agency execution workspace; "
        f"the market research is conducted for {client_name}.\n"
        f"3. Decompose and investigate actual competitors operating within {client_name}'s specific industry category "
        f"({industry}) and geographic market ({location or 'regional market'})."
    )


async def plan_scoping_node(state: DeepResearchState) -> dict[str, Any]:
    """
    Decomposes the complex user research query into 2 to 4 structured sub-topics.
    Guarantees client brand grounding and entity isolation: if competitors are named in the query,
    each competitor receives a dedicated sub-topic to prevent research starvation.
    """
    query = state["query"]
    context = state.get("context")
    on_event = state.get("on_event_fn")
    
    if on_event:
        try:
            await on_event({
                "type": "status",
                "stage": "planning",
                "message": "Deep Research Supervisor: Decomposing research query into structured investigation facets...",
            })
        except Exception:
            pass

    brand_block = _format_brand_context_block(context, query)
    brand_section = f"\n{brand_block}\n" if brand_block else ""

    plan_prompt = f"""You are the Deep Research Supervisor for AgencyOS Campaign Intelligence.
Analyze the user research query and decompose it into 2 to 4 structured sub-investigation facets.
{brand_section}
USER QUERY: "{query}"

MANDATORY PLANNING RULES:
1. CLIENT BRAND ANCHORING: If the query mentions 'our brand', 'we', 'us', 'our competitors', or asks open-ended strategic questions (e.g. 'what are our direct and indirect competitors?'), anchor the entire investigation specifically to the ACTIVE CLIENT BRAND defined above. For competitor inquiries, generate sub-topics covering:
   - Direct Competitors: Brands offering similar products/services in the same industry category and local geography.
   - Indirect Competitors: Alternatives, substitutes, delivery platforms, or adjacent category providers.
   - Core Offerings & Value Comparison: Pricing tiers, signature products/dishes, or customer sentiment.
2. ENTITY ISOLATION: If specific competitor companies, brands, or products are named in the query (e.g. 'Blue Tokai', 'Subko', 'Third Wave Coffee'), you MUST allocate at least one dedicated sub-topic to EACH named competitor entity. Do NOT bundle all competitors into a single generic search.
3. DIMENSION ACCOUNTING: Ensure specific requested dimensions (e.g. pricing tiers, subscription models, seasonal gift bundles, customer review complaints) are explicitly captured in the research_questions.
4. BUDGET ALLOCATION: Allocate 1 or 2 tool calls per sub-topic. Total tool calls across all sub-topics must not exceed {state.get('max_global_budget', 6)}.
5. SEARCH QUERY PRECISION: Provide specific, keyword-rich search queries targeting primary sources (menus, pricing tables, reviews, official stores). Include relevant local geography (e.g. city/neighborhood) when investigating local businesses."""

    try:
        plan = await invoke_structured_llm(
            prompt=plan_prompt,
            schema_class=DeepResearchPlan,
            model=settings.MARKET_RESEARCH_MODEL,
            temperature=0.1,
        )
    except Exception as e:
        logger.warning(f"Structured plan generation failed ({e}); using heuristic fallback plan.")
        client_name = context.client_name if context else "Client Brand"
        industry = context.client_industry if context else "Industry"
        # Fallback plan decomposing query by entity or default facets
        plan = DeepResearchPlan(
            plan_summary=f"Default faceted research plan targeting competitive landscape and market whitespace for {client_name}.",
            sub_topics=[
                ResearchSubTopic(
                    topic_id="topic_direct_competitors",
                    title=f"Direct Competitors & Offerings ({industry})",
                    research_questions=["What are the verified competitor pricing tiers and core products?"],
                    suggested_queries=[f"{client_name} {industry} competitors pricing"],
                    max_tool_budget=2,
                ),
                ResearchSubTopic(
                    topic_id="topic_indirect_whitespace",
                    title="Indirect Competitors & Customer Whitespace",
                    research_questions=["What are common customer pain points or unmet needs in this market?"],
                    suggested_queries=[f"{client_name} {industry} reviews complaints whitespace"],
                    max_tool_budget=2,
                ),
            ],
        )

    topic_titles = [t.title for t in plan.sub_topics]
    log_msg = f"Deep Research Supervisor generated {len(plan.sub_topics)} investigation facets: {', '.join(topic_titles)}."
    
    if on_event:
        try:
            await on_event({"type": "turn_start", "message": log_msg})
        except Exception:
            pass

    return {
        "plan": plan,
        "current_topic_idx": 0,
        "activity_logs": [log_msg],
    }


